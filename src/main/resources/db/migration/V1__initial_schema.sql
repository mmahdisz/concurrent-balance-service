CREATE TABLE accounts (
    id VARCHAR(255) PRIMARY KEY,
    balance BIGINT NOT NULL CHECK (balance >= 0)
);

CREATE TABLE processed_transactions (
    transaction_id VARCHAR(255) PRIMARY KEY,
    operation_type VARCHAR(16) NOT NULL,
    primary_account_id VARCHAR(255) NOT NULL REFERENCES accounts(id),
    secondary_account_id VARCHAR(255) REFERENCES accounts(id),
    amount BIGINT NOT NULL CHECK (amount > 0),
    processed_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Written atomically with balances and receipts; no Kafka network IO on the request thread.
CREATE TABLE kafka_outbox (
    sequence_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id VARCHAR(36) NOT NULL UNIQUE,
    account_id VARCHAR(255) NOT NULL,
    payload TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE kafka_outbox_lock (
    id INTEGER PRIMARY KEY CHECK (id = 1)
);
