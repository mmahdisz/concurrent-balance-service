import { expect, test } from '@playwright/test';
test('real accounts, transfer, replay, rejection, lab and API inspection', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  const prefix = 'browser-' + Date.now(), a = prefix + '-A', b = prefix + '-B';
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('/');
  await expect(page.getByText('Service connected')).toBeVisible();
  await page.getByRole('link', { name: 'Accounts', exact: true }).click();
  for (const id of [a,b]) {
    await page.getByRole('button', { name: 'New account', exact: true }).click();
    await page.getByLabel('Account ID', { exact: true }).fill(id);
    await page.getByLabel('Initial balance').fill('1000');
    await page.getByRole('button', { name: 'Create account', exact: true }).last().click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
  }
  await page.getByRole('link', { name: 'Transactions', exact: true }).click();
  await page.getByLabel('From account').fill(a);
  await page.getByLabel('To account').fill(b);
  await page.getByLabel('Amount · whole units').fill('80');
  const tx = await page.getByLabel('Transaction ID', { exact: true }).inputValue();
  await page.getByRole('button', { name: 'Submit transfer' }).click();
  await expect(page.getByRole('status')).toContainText('Acknowledged');
  await page.getByRole('button', { name: 'Submit transfer' }).click();
  await expect(page.getByRole('status')).toContainText('Acknowledged');
  await page.getByLabel('Filter history by exact account ID').fill(a);
  await page.getByRole('button', { name: 'Filter', exact: true }).click();
  await expect(page.getByRole('button', { name: tx, exact: true })).toHaveCount(1);
  await page.getByRole('button', { name: tx, exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('Committed transaction');
  await page.keyboard.press('Escape');
  await expect(page.getByRole('button', { name: tx, exact: true })).toBeFocused();
  await page.getByRole('button', { name: 'Generate a new transaction ID' }).click();
  await page.getByLabel('Amount · whole units').fill('9999');
  await page.getByRole('button', { name: 'Submit transfer' }).click();
  await expect(page.getByRole('status')).toContainText(/insufficient/i);
  await page.getByRole('link', { name: 'API inspector', exact: true }).click();
  await expect(page.getByText('409', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Inspect', exact: false }).first().click();
  await expect(page.getByRole('dialog')).toContainText('Request body');
  await expect(page.getByRole('dialog')).toContainText('INSUFFICIENT_FUNDS');
  await page.keyboard.press('Escape');
  await page.getByRole('link', { name: /Concurrency lab/ }).click();
  await page.getByRole('button', { name: 'Run experiment', exact: true }).click();
  await expect(page.getByText('Experiment results', { exact: true })).toBeVisible();
  await expect(page.locator('.checks .pass')).toHaveCount(3);
  await page.getByRole('button', { name: /One ID, many requests/ }).click();
  await page.getByRole('button', { name: 'Run experiment', exact: true }).click();
  await expect(page.getByText('Executing on the server…')).toHaveCount(0);
  await expect(page.locator('.run-stats').getByText('1', { exact: true })).toBeVisible();
  await expect(page.locator('.checks .pass')).toHaveCount(3);
  await page.getByRole('link', { name: 'Overview', exact: true }).click();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: 'test-results/overview-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/overview-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
test('connection failure is visible and retry recovers', async ({ page }) => {
  await page.route('**/api/console/snapshot?*', route => route.abort());
  await page.goto('/');
  await expect(page.getByRole('alert')).toContainText('Cannot reach');
  await page.unroute('**/api/console/snapshot?*');
  await page.getByRole('button', { name: 'Retry', exact: true }).click();
  await expect(page.getByText('Service connected')).toBeVisible();
});
